-- 0010 · BRYT VISION EDIT add-on fulfillment tracking. ADDITIVE ONLY.
-- Adds new columns to the private edit_orders table. Nothing is dropped, rewritten or deleted, and no existing
-- row's current values are changed (existing rows simply receive the column defaults, e.g. 'awaiting_shipment').
-- edit_orders stays PRIVATE (row level security on, no policies, no grants to anon/authenticated); new columns inherit that.
-- Run AFTER 0007 (which created edit_orders). Independent of 0008/0009.
--
-- The existing `status` column is kept exactly as is (the cleanup job uses it to decide when original footage may be
-- released). The app mirrors the new edit_status into it.

alter table public.edit_orders
  add column if not exists order_number          bigint generated by default as identity (start with 1001),
  add column if not exists shirt_status          text not null default 'awaiting_shipment'
    check (shirt_status in ('awaiting_shipment','preparing_shipment','shipped','delivered')),
  add column if not exists edit_status           text not null default 'awaiting_edit'
    check (edit_status in ('awaiting_edit','editing_in_progress','edit_completed','delivered')),
  add column if not exists shirt_carrier         text,
  add column if not exists shirt_tracking_number text,
  add column if not exists shirt_shipped_at      timestamptz,
  add column if not exists shirt_delivered_at    timestamptz,
  add column if not exists tracking_emailed_at   timestamptz,
  add column if not exists admin_notified_at     timestamptz;

-- Human-friendly order numbers (BV-1001, BV-1002, ...) must be unique.
create unique index if not exists edit_orders_order_number_key on public.edit_orders (order_number);
